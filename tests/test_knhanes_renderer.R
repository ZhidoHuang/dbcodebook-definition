args <- commandArgs(trailingOnly=TRUE)
root <- normalizePath(".")
source(file.path(root,"scripts/check_public_raw_reads.R"), encoding="UTF-8")
source(file.path(root,"scripts/render_definition_bundle.R"), encoding="UTF-8")
passed <- character()
ok <- function(name, expr) { force(expr); passed <<- c(passed,name) }
reject <- function(name, expr) { value <- tryCatch({force(expr);FALSE}, error=function(e)TRUE); if (!value) stop("Expected rejection: ",name); passed <<- c(passed,name) }
read_code <- c('dt <- read.csv("raw_data.csv", colClasses=c(id="character"))','name_z <- read.csv("raw_codebook.csv")')
ok("KNHANES direct character read",check_public_raw_reads(read_code,"KNHANES"))
reject("KNHANES default numeric coercion",check_public_raw_reads(c('dt <- read.csv("raw_data.csv")',read_code[[2]]),"KNHANES"))
reject("nonidentity colClasses",check_public_raw_reads(c('dt <- read.csv("raw_data.csv", colClasses=c(id="character",sex="character"))',read_code[[2]]),"KNHANES"))
reject("extra fileEncoding",check_public_raw_reads(c('dt <- read.csv("raw_data.csv", colClasses=c(id="character"),fileEncoding="UTF-8")',read_code[[2]]),"KNHANES"))
special_dir <- tempfile("knhanes-personal-")
dir.create(special_dir)
dictionary <- data.frame(Variable="voc_x (Indoor air quality special release)",
  `File type`="uniqID",newname="voc",check.names=FALSE)
write.csv(dictionary,file.path(special_dir,"raw_codebook.csv"),row.names=FALSE)
special_read <- c('dt <- read.csv("raw_data_Indoor_air_quality_special_release.csv", colClasses=c(ID="character", id="character", year="character"))',read_code[[2]])
ok("dictionary-bound standalone personal read",check_public_raw_reads(special_read,"KNHANES",special_dir))
reject("standalone cannot be renamed Core",check_public_raw_reads(read_code,"KNHANES",special_dir))
reject("standalone cannot use other family's name",check_public_raw_reads(sub("Indoor_air_quality","Cycle_7_oral",special_read),"KNHANES",special_dir))
reject("unbound standalone filename",check_public_raw_reads(special_read,"KNHANES",tempdir()))
reject("extra repeat read in personal definition",check_public_raw_reads(c(special_read,'other <- read.csv("raw_data_Dietary_recall_detail.csv")'),"KNHANES",special_dir))
dictionary$`File type` <- "reID"
write.csv(dictionary,file.path(special_dir,"raw_codebook.csv"),row.names=FALSE)
reject("repeat dictionary cannot enter personal reader",check_public_raw_reads(special_read,"KNHANES",special_dir))
dictionary$`File type` <- "uniqID"
dictionary <- rbind(dictionary,
  data.frame(Variable="sex (Core data)",`File type`="uniqID",newname="sex",check.names=FALSE))
write.csv(dictionary,file.path(special_dir,"raw_codebook.csv"),row.names=FALSE)
reject("mixed samples require both reads",check_public_raw_reads(special_read,"KNHANES",special_dir))
mixed_read <- c(sub("^dt <-", "dt_special <-", special_read[[1]]),
  sub("^dt <-", "dt_core <-", read_code[[1]]), read_code[[2]])
ok("mixed samples preserve two literal source reads",check_public_raw_reads(mixed_read,"KNHANES",special_dir))
reject("mixed samples cannot redirect special to core",check_public_raw_reads(sub("raw_data_Indoor_air_quality_special_release.csv", "raw_data.csv", mixed_read, fixed=TRUE),"KNHANES",special_dir))
unlink(special_dir,recursive=TRUE)
ok("CHARLS existing simple reads",check_public_raw_reads(c('dt <- read.csv("raw_data.csv")',read_code[[2]]),"CHARLS"))
ok("SHARE existing identity read",check_public_raw_reads(c('dt <- read.csv("raw_data.csv", colClasses=c(mergeid="character"))',read_code[[2]]),"SHARE"))
frame <- data.frame(ID=c("2007_001","2008_001"),id=c("001","001"),year=c(2007L,2008L),sex=c(1L,2L))
ok("render permits same id different year",validate_knhanes_render_inputs(list(frame,frame,frame),c("2007","2008")))
reject("render rejects repeated person-year",validate_knhanes_render_inputs(list(rbind(frame,frame[1,])),c("2007","2008")))
mixed <- rbind(transform(frame,sample_source="Core data"),transform(frame,sample_source="Indoor air quality special release"))
ok("render keeps coinciding identifiers in distinct samples",validate_knhanes_render_inputs(list(mixed),c("2007","2008")))
ok("final output guard uses the same sample identity",validate_person_period_outputs(list(mixed),"KNHANES"))
reject("final output guard rejects same-sample duplicates",validate_person_period_outputs(list(rbind(mixed,mixed[1,])),"KNHANES"))
reject("render rejects duplicates within sample",validate_knhanes_render_inputs(list(rbind(mixed,mixed[1,])),c("2007","2008")))
bad <- frame;bad$id <- as.integer(bad$id)
reject("render rejects numeric id",validate_knhanes_render_inputs(list(bad),c("2007","2008")))
bad <- frame;bad$ID[[1]] <- "2007_1"
reject("render checks derived identity",validate_knhanes_render_inputs(list(bad),c("2007","2008")))
reject("render rejects invented year",validate_knhanes_render_inputs(list(frame),c("2006","2007","2008")))
reject("render requires explicit order",validate_knhanes_render_inputs(list(frame),c("2008","2007")))
